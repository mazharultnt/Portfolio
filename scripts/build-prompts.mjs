// Rebuilds IMAGE_PROMPTS.md (in Bengali instructions) from src/data/images.ts
// Run with:  npm run prompts
import { writeFileSync } from "node:fs";
import { images } from "../src/data/images.ts";

const entries = Object.values(images);
const total = entries.length;

let out = `# ছবির প্রম্পট চেকলিস্ট (মোট ${total}টি ছবি)

## কীভাবে কাজ করবে (প্রতিটা ছবির জন্য একই ধাপ)

1. নিচের প্রতিটা ছবির বক্সে **"ChatGPT-কে এটা দাও"** লেখা কোড বক্স থেকে প্রম্পটটা কপি করো।
2. ChatGPT-তে নতুন মেসেজে পেস্ট করে ছবি বানাতে বলো।
3. ছবি পছন্দ হলে ডাউনলোড করো।
4. ছবির নাম বদলে ঠিক সেই নাম দাও, যেটা **"ছবির ফাইল নাম"** লেখা আছে (বানান, ড্যাশ, .jpg/.png সব হুবহু)।
5. ফাইলটা প্রজেক্টের \`public/images/\` ফোল্ডারে রাখো।
6. ব্রাউজারে রিফ্রেশ করলেই ছবি বসে যাবে।

## জরুরি টিপস

- **কালার ও স্টাইল:** সব প্রম্পটে রঙিন, ঝকঝকে, থ্রিডি (3D) স্টাইল দেওয়া আছে, যাতে সাদা ওয়েবসাইটে ছবিগুলো ফুটে ওঠে।
- **সাইজ:** ChatGPT সাধারণত স্কয়ার (১:১), লম্বা (২:৩) আর চওড়া (৩:২) ছবি দেয়। একদম হুবহু সাইজ না হলেও সমস্যা নেই, ওয়েবসাইট নিজে ছবি কেটে বসিয়ে নেয়। চওড়া ব্যানারের ক্ষেত্রে ৩:২ চওড়া ছবি চাইলেই হবে।
- **লেখা থাকলে:** ছবির ভেতরে কোনো লেখা এলে ChatGPT-কে বলো "Regenerate without any text".
- **একই স্টাইল রাখতে:** একই চ্যাটে সবগুলো ছবি বানালে স্টাইল প্রায় একই থাকে।
- **ফাইলের ধরন:** ডাউনলোড PNG হলে আর নাম .jpg দিলেও সাধারণত ব্রাউজারে দেখায়। পরিষ্কার রাখতে চাইলে প্রম্পটের নামের এক্সটেনশনই ব্যবহার করো।
- **সার্টিফিকেট (certificate-1, certificate-2):** এগুলো AI দিয়ে বানাবে না। নিজের আসল ডকুমেন্ট স্ক্যান করে দেবে (ব্যক্তিগত নম্বর ঢেকে)।

`;

entries.forEach((e, i) => {
  const isReal = e.prompt.startsWith("USE YOUR REAL");
  out += `
==================================================
## ছবি ${i + 1} / ${total}

**ছবির ফাইল নাম (ঠিক এই নামেই সেভ করবে):** \`${e.file}\`
**কোন ফোল্ডারে রাখবে:** \`public/images/${e.file}\`
**ওয়েবসাইটের কোথায় বসবে:** ${e.where}
**সাইজ / অনুপাত:** ${e.ratio} (${e.size})

`;
  if (isReal) {
    out += e.file.startsWith("mazharul-")
      ? `**এই ছবি AI দিয়ে বানাবে না।** এটা তোমার নিজের আসল ছবি, প্রজেক্টে আগে থেকেই দেওয়া আছে।\n`
      : `**এই ছবি AI দিয়ে বানাবে না।** এখানে তোমার আসল ডকুমেন্টের স্ক্যান বা ছবি দেবে (ব্যক্তিগত নম্বর ঢেকে)। এখনো না থাকলে ফাঁকা রাখো, ওয়েবসাইটে সুন্দর placeholder থাকবে। AI দিয়ে নকল সার্টিফিকেট বানালে ভুল তথ্য দেওয়া হয়।\n`;
  } else {
    out += `**ChatGPT-কে এটা দাও (কপি করে পেস্ট করো):**

\`\`\`
${e.prompt} Aspect ratio: ${e.ratio}.
\`\`\`
`;
  }
  out += `
**ছবি ডাউনলোড করে নাম দাও:** \`${e.file}\`  ->  \`public/images/\` ফোল্ডারে রাখো
`;
});

writeFileSync("IMAGE_PROMPTS.md", out);
console.log(`Wrote IMAGE_PROMPTS.md with ${total} entries`);
